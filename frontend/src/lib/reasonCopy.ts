/** A code never creates an action: the caller must supply an available local destination. */
export function reasonCopy(
  code: string | null | undefined,
  context: ReasonContext = {},
): ReasonCopy {
  const entry = code && Object.hasOwn(COPY, code) ? COPY[code] : undefined;
  if (!entry) return { message: UNAVAILABLE_REASON, action: null };
  const text =
    typeof entry === "string"
      ? entry
      : ((context.surface ? entry[context.surface] : undefined) ?? entry.default);
  const scope = [
    context.month && `Месяц: ${context.month}`,
    context.account && `Счёт: ${context.account}`,
    context.instrument && `Инструмент: ${context.instrument}`,
  ]
    .filter(Boolean)
    .join(" · ");
  const kind = code && Object.hasOwn(ACTIONS, code) ? ACTIONS[code] : undefined;
  const target = kind ? context.actions?.[kind] : undefined;
  const available =
    !context.closed &&
    target?.available &&
    target.href.startsWith("/v2/") &&
    !target.href.includes("\\");
  return {
    message: scope ? `${text} ${scope}.` : text,
    action: available && target ? { label: "Исправить", href: target.href } : null,
  };
}
